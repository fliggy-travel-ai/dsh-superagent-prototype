test('同步副本与原型源文件没有漂移', () => {
  const roots = vendorRoots();
  assert.deepEqual(syncVendor({ check: true, prototypeRoot: roots.prototypeRoot, vendorRoot: roots.vendorRoot }), []);
});

test('同步副本只改导入并写入来源头', () => {
  const roots = vendorRoots();
  for (const file of vendorFiles) {
    const original = readFileSync(join(roots.prototypeRoot, file.source), 'utf8');
    const copy = readFileSync(join(roots.vendorRoot, file.target), 'utf8');
    const [header, ...rest] = copy.split('\n');
    assert.match(header ?? '', new RegExp(`^// Generated by scripts/vendor-sync\\.ts from ${file.source.replaceAll('/', '\\/')} \\(sha256:[0-9a-f]{16}\\)`));
    const strip = (text: string) => text.split('\n').filter(line => !/^import .* from '/.test(line)).join('\n');
    assert.equal(strip(rest.join('\n')), strip(original));
  }
});

test('原型源文件变化时检查失败，生成后恢复一致', () => {
  const root = mkdtempSync(join(tmpdir(), 'ghsub-vendor-'));
  try {
    const roots = vendorRoots();
    const prototypeRoot = join(root, 'prototype');
    const vendorRoot = join(root, 'vendor');
    for (const file of vendorFiles) {
      const target = join(prototypeRoot, file.source);
      mkdirpWrite(target, readFileSync(join(roots.prototypeRoot, file.source), 'utf8'));
    }
    assert.equal(syncVendor({ check: false, prototypeRoot, vendorRoot }).length, vendorFiles.length);
    assert.deepEqual(syncVendor({ check: true, prototypeRoot, vendorRoot }), []);
    writeFileSync(join(prototypeRoot, 'src/infra/text.ts'), `${readFileSync(join(prototypeRoot, 'src/infra/text.ts'), 'utf8')}\nexport const changed = 1\n`);
    assert.deepEqual(syncVendor({ check: true, prototypeRoot, vendorRoot }), ['text.ts']);
    assert.deepEqual(syncVendor({ check: true, prototypeRoot, vendorRoot }), ['text.ts']);
    syncVendor({ check: false, prototypeRoot, vendorRoot });
    assert.deepEqual(syncVendor({ check: true, prototypeRoot, vendorRoot }), []);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

function mkdirpWrite(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

test('复用的纯函数在副本里可用', () => {
  assert.equal(isHumanLogin({ login: 'dependabot[bot]' }), false);
  assert.deepEqual(githubAddress('https://github.com/Org/App/pull/7#discussion_r9', 'org/app'), { number: 7, pr: true, discussion: 9 });
  const snapshot = { head: 'abcdef1234', checks: [{ name: 'test', status: 'completed', conclusion: 'failure' }], statuses: [] };
  assert.deepEqual(ciCounts(snapshot), { failed: 1, running: 0 });
  assert.deepEqual(ciFailures(snapshot), ['test']);
  assert.match(ciSummary(snapshot, 'main', 'x'), /^CI failed 1\/1 on main at abcdef1: test/);
  const trigger = commentTrigger({ id: 1, body: 'hi', user: { login: 'a' }, html_url: 'u', updated_at: 't' }, { number: 3, isPr: false }, 'conversation', 'me');
  assert.equal(trigger.text, 'hi');
});

test('副本里的 readGithub 经 fetch 适配器读取 Issue 和评论分页', async () => {
  const urls: string[] = [];
  const fetchImpl = (async (input: URL | RequestInfo) => {
    const url = new URL(String(input));
    urls.push(url.pathname + url.search);
    if (url.pathname.endsWith('/comments')) {
      return new Response(JSON.stringify([{ id: 5, body: 'c', user: { login: 'a' }, created_at: 't', html_url: 'u' }]));
    }
    return new Response(JSON.stringify({
      id: 1, number: 3, title: 'T', state: 'open', body: 'b', user: { login: 'a' }, created_at: 't', html_url: 'u',
    }));
  }) as typeof fetch;
  const client = new GithubClient({ token: 'tok', fetch: fetchImpl, now: () => 0 });
  const commands = new RepositoryCommands(client, 'org/app');
  const issue = await readGithub(commands, 'github/issues/3') as { title: string };
  assert.equal(issue.title, 'T');
  const page = await readGithub(commands, 'github/issues/3/comments/1') as { messages: Array<{ text: string }> };
  assert.equal(page.messages[0]?.text, 'c');
  assert.deepEqual(urls, ['/repos/org/app/issues/3', '/repos/org/app/issues/3/comments?per_page=20&page=1']);
  await assert.rejects(commands.api(z.unknown(), 'https://evil.example.com/x'), /路径无效/);
});
