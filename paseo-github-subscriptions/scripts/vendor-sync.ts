import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export interface VendorFile { source: string; target: string }

export const vendorFiles: VendorFile[] = [
  { source: 'src/infra/text.ts', target: 'text.ts' },
  { source: 'src/sources/github-trigger.ts', target: 'github-trigger.ts' },
  { source: 'src/sources/github-read.ts', target: 'github-read.ts' },
];

const importMap: Array<[string, string]> = [
  ["'../core/index.ts'", "'./shim.ts'"],
  ["'../infra/commands.ts'", "'./shim.ts'"],
  ["'./kind.ts'", "'./shim.ts'"],
  ["'../infra/text.ts'", "'./text.ts'"],
];

export function vendorContent(source: string, text: string): string {
  const digest = createHash('sha256').update(text).digest('hex').slice(0, 16);
  const body = importMap.reduce((current, [from, to]) => current.replaceAll(` from ${from}`, ` from ${to}`), text);
  const header = `// Generated by scripts/vendor-sync.ts from ${source} (sha256:${digest}). Do not edit by hand.\n`;
  return header + body;
}

export function vendorRoots(scriptUrl: string = import.meta.url) {
  const pluginRoot = join(dirname(fileURLToPath(scriptUrl)), '..');
  return { pluginRoot, prototypeRoot: join(pluginRoot, '..'), vendorRoot: join(pluginRoot, 'server/vendor/dsh-superagent') };
}

export function syncVendor(options: { check: boolean; prototypeRoot: string; vendorRoot: string }): string[] {
  const drifted: string[] = [];
  mkdirSync(options.vendorRoot, { recursive: true });
  for (const file of vendorFiles) {
    const expected = vendorContent(file.source, readFileSync(join(options.prototypeRoot, file.source), 'utf8'));
    const targetPath = join(options.vendorRoot, file.target);
    let current: string | null = null;
    try { current = readFileSync(targetPath, 'utf8'); } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    }
    if (current === expected) continue;
    drifted.push(file.target);
    if (!options.check) writeFileSync(targetPath, expected);
  }
  return drifted;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  const roots = vendorRoots();
  const drifted = syncVendor({ check, prototypeRoot: roots.prototypeRoot, vendorRoot: roots.vendorRoot });
  if (check && drifted.length) {
    console.error(`同步副本与原型源文件不一致：${drifted.join('、')}。运行 node scripts/vendor-sync.ts 重新生成。`);
    process.exit(1);
  }
  console.log(check ? '同步副本与原型源文件一致' : drifted.length ? `已更新：${drifted.join('、')}` : '同步副本已是最新');
}
